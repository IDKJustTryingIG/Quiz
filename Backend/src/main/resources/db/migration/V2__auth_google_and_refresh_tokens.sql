-- Google sign-in columns, roles, and the refresh-token / exchange-code tables.

-- Google-only accounts never have a password.
ALTER TABLE users ALTER COLUMN password DROP NOT NULL;

ALTER TABLE users ADD COLUMN IF NOT EXISTS role            VARCHAR(20);
ALTER TABLE users ADD COLUMN IF NOT EXISTS login_type      VARCHAR(20);
ALTER TABLE users ADD COLUMN IF NOT EXISTS google_id       VARCHAR(255);
ALTER TABLE users ADD COLUMN IF NOT EXISTS profile_picture VARCHAR(500);

-- Backfill before tightening, so an already-populated table survives the change.
UPDATE users SET role       = 'USER'  WHERE role       IS NULL;
UPDATE users SET login_type = 'LOCAL' WHERE login_type IS NULL;

ALTER TABLE users ALTER COLUMN role       SET NOT NULL;
ALTER TABLE users ALTER COLUMN login_type SET NOT NULL;

-- Partial unique index: many rows may have no google_id, but a linked one is unique.
CREATE UNIQUE INDEX IF NOT EXISTS uk_users_google_id
    ON users (google_id) WHERE google_id IS NOT NULL;

-- Case-insensitive uniqueness for usernames, matching existsByUsernameIgnoreCase.
-- The plain uk_users_username constraint alone is case-sensitive and would let
-- "abhi" and "Abhi" both exist.
CREATE UNIQUE INDEX IF NOT EXISTS uk_users_username_lower
    ON users (LOWER(username));

CREATE TABLE IF NOT EXISTS refresh_tokens (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT       NOT NULL REFERENCES users (user_id) ON DELETE CASCADE,
    -- SHA-256 hex of the raw token; the raw value is never stored.
    token_hash     CHAR(64)     NOT NULL,
    issued_at      TIMESTAMP(6) NOT NULL,
    expires_at     TIMESTAMP(6) NOT NULL,
    revoked_at     TIMESTAMP(6),
    replaced_by_id BIGINT,
    user_agent     VARCHAR(255),
    client_ip      VARCHAR(45),
    CONSTRAINT uk_refresh_tokens_hash UNIQUE (token_hash)
);

CREATE INDEX IF NOT EXISTS idx_refresh_tokens_user     ON refresh_tokens (user_id);
CREATE INDEX IF NOT EXISTS idx_refresh_tokens_expires  ON refresh_tokens (expires_at);

CREATE TABLE IF NOT EXISTS oauth_exchange_codes (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT       NOT NULL REFERENCES users (user_id) ON DELETE CASCADE,
    code_hash   CHAR(64)     NOT NULL,
    expires_at  TIMESTAMP(6) NOT NULL,
    consumed_at TIMESTAMP(6),
    CONSTRAINT uk_oauth_codes_hash UNIQUE (code_hash)
);

CREATE INDEX IF NOT EXISTS idx_oauth_codes_expires ON oauth_exchange_codes (expires_at);
